#!/usr/bin/env python3
"""Write recomp/host/gbk_table.h: CP936 (GBK) <-> UTF-16 tables for the Chinese build (T123_GBK).
Same shape as sjis_table.h: gbk_decode[(lead-0x81)*191 + (trail-0x40)] (0 = unmapped) and
gbk_encode[], sorted by code point, for the reverse direction. Generated from Python's cp936."""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "recomp/host/gbk_table.h"
decode, encode = [], {}
for lead in range(0x81, 0xFF):
    for trail in range(0x40, 0xFF):
        try:
            u = bytes([lead, trail]).decode("cp936")
        except UnicodeDecodeError:
            u = ""
        code = ord(u) if len(u) == 1 and ord(u) <= 0xFFFF else 0
        decode.append(code)
        if code and code not in encode:
            encode[code] = lead << 8 | trail
lines = ["/* Generated by tools/gen_gbk_table.py from Python's cp936 codec. */",
         "#ifndef T123_GBK_TABLE_H", "#define T123_GBK_TABLE_H", "#include <stdint.h>",
         "static const uint16_t gbk_decode[] = {"]
for i in range(0, len(decode), 12):
    lines.append("    " + ",".join(f"0x{v:04x}" for v in decode[i:i + 12]) + ",")
lines += ["};", "typedef struct { uint16_t unicode, bytes; } GbkPair;", "static const GbkPair gbk_encode[] = {"]
pairs = sorted(encode.items())
for i in range(0, len(pairs), 6):
    lines.append("    " + ",".join(f"{{0x{u:04x},0x{b:04x}}}" for u, b in pairs[i:i + 6]) + ",")
lines += ["};", "#endif", ""]
OUT.write_text("\n".join(lines), encoding="ascii")
print(f"{OUT}: {len(decode)} decode entries, {len(pairs)} encode pairs")
